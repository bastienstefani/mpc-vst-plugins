#!/usr/bin/env python3
"""Writes vst/layout.conf, Philtre's skin, for a 4-knob MPC (Live II, One, Key 37): every Q-Link column is one frame of
four controls stacked top to bottom, in the order of the four physical knobs; the Q-Link button moves to the next
column and qlink_bounds=column outlines it. Frames stay left of x=1010 (MPC's Q-Link sidebar covers x >= ~1025 while a
knob is touched); the strip on the right carries help text only.

    python3 vst/make_layout.py        (from ports/philtre; commit the output)
"""
import os

import make_params as mp

HERE = os.path.dirname(os.path.abspath(__file__))
X = [10 + 252 * c for c in range(4)]          # frame x per column
CX = [x + 122 for x in X]                     # control centre x
TOPS = [136, 276, 416, 556]                   # slot tops
INK2 = "9a93a8"

THEME = """theme_bg=0c0b10
theme_panel=141219
theme_line=2c2836
theme_ink=ece8f4
theme_ink_dim=9a93a8
theme_ink_faint=5c566a
theme_accent=b48cff
theme_accent_hi=e0d2ff
theme_knob_face=1d1a24
theme_knob_ring=3a3448
theme_knob_dot=b48cff
theme_lcd=110f16
theme_btn_text=0c0b10
theme_tile_on=2a2338
theme_seg_active=b48cff
theme_seg_inactive=18161e
theme_seg_active_tx=0c0b10
qlink_bounds=column
"""

out = ["# generated by vst/make_layout.py: edit that script, not this file", THEME]


def frame(c, title, banks=None):
    out.append('frame x=%d y=96 w=244 h=608 title="%s"%s' % (X[c], title, bk(banks)))


def bk(banks):
    return ' banks="%s"' % banks if banks else ""


def ctl(c, slot, kind, label, key, banks=None, **kw):
    """one control in slot 0..3 of column c"""
    cx, top = CX[c], TOPS[slot]
    extra = "".join(" %s=%s" % (k, v) for k, v in kw.items())
    if kind == "knob":
        out.append('knob cx=%d cy=%d r=28 label="%s" key=%s%s%s' % (cx, top + 38, label, key, extra, bk(banks)))
    elif kind == "popup":
        out.append('popup cx=%d cy=%d w=216 h=44 label="%s" key=%s%s%s' % (cx, top + 64, label, key, extra, bk(banks)))
    elif kind == "seg":
        n = kw.pop("n", 2)
        extra = "".join(" %s=%s" % (k, v) for k, v in kw.items())
        out.append('enum_h cx=%d cy=%d label="%s" key=%s sw=%d%s%s' % (cx, top + 64, label, key, 208 // n, extra, bk(banks)))
    elif kind == "stepper":
        out.append('stepper cx=%d cy=%d w=216 h=48 label="%s" key=%s%s%s' % (cx, top + 64, label, key, extra, bk(banks)))


def help_text(lines, banks=None):
    out.append('frame x=1022 y=96 w=248 h=608 title="PHILTRE"%s' % bk(banks))
    y = 156
    for ln in lines:
        if ln:
            out.append('text cx=1146 cy=%d label="%s" size=1.3 color=%s font="Titillium Web" weight=400%s' % (y, ln, INK2, bk(banks)))
        y += 26


def qlinks(title, keys):
    assert len(keys) == 16, (title, len(keys))
    out.append('qlinks "%s" = %s' % (title, ",".join(keys)))


# ---- MAIN ----
out.append("\n[tab MAIN]")
frame(0, "MACROS")
for m in range(4):
    ctl(0, m, "knob", "MACRO %d" % (m + 1), "mac%d" % (m + 1))
frame(1, "VOICE")
ctl(1, 0, "seg", "MODE", "mode", n=3)
ctl(1, 1, "knob", "VOICES", "voices")
ctl(1, 2, "knob", "GLIDE", "glide")
ctl(1, 3, "knob", "BEND RANGE", "bend")
frame(2, "OUTPUT")
ctl(2, 0, "knob", "VOLUME", "vol")
ctl(2, 1, "knob", "VELOCITY", "vel")
frame(3, "FILTER")
ctl(3, 0, "knob", "CUTOFF", "f_cut")
ctl(3, 1, "knob", "RESONANCE", "f_res")
ctl(3, 2, "knob", "DRIVE", "f_drive")
ctl(3, 3, "knob", "ENV 2 AMT", "f_env")
help_text(["Macros are mod", "sources: route them", "on the MOD page", "", "Q-LINK button:", "next column", "",
           "Touch a control,", "then the wheel", "steps it"])
qlinks("MAIN", ["mac1", "mac2", "mac3", "mac4", "mode", "voices", "glide", "bend", "vol", "vel", "-", "-",
                "f_cut", "f_res", "f_drive", "f_env"])

# ---- OSC A / OSC B ----
for o in ("a", "b"):
    O = o.upper()
    out.append("\n[tab OSC %s]" % O)
    frame(0, "OSC %s WAVE" % O)
    ctl(0, 0, "stepper", "TABLE", "%s_table" % o)
    ctl(0, 1, "knob", "WT POS", "%s_pos" % o)
    ctl(0, 2, "popup", "WARP", "%s_warp" % o)
    ctl(0, 3, "knob", "WARP AMT", "%s_wamt" % o)
    frame(1, "PITCH / LEVEL")
    ctl(1, 0, "knob", "OCTAVE", "%s_oct" % o)
    ctl(1, 1, "knob", "SEMI", "%s_semi" % o)
    ctl(1, 2, "knob", "FINE", "%s_fine" % o)
    ctl(1, 3, "knob", "LEVEL", "%s_level" % o)
    frame(2, "UNISON")
    ctl(2, 0, "knob", "VOICES", "%s_uni" % o)
    ctl(2, 1, "knob", "DETUNE", "%s_det" % o)
    ctl(2, 2, "knob", "BLEND", "%s_blend" % o)
    ctl(2, 3, "knob", "WIDTH", "%s_width" % o)
    frame(3, "PHASE / OUT")
    ctl(3, 0, "knob", "PHASE", "%s_phase" % o)
    ctl(3, 1, "knob", "RANDOM", "%s_rand" % o)
    ctl(3, 2, "knob", "PAN", "%s_pan" % o)
    ctl(3, 3, "seg", "OSC %s" % O, "%s_on" % o)
    help_text(["Tables: 12 built in,", "then your .wav files", "in the plugin's", "wavetables folder", "",
               "FM / AM / RM use", "the other oscillator" if o == "a" else "oscillator A", "",
               "Random: start phase", "spread per note"])
    qlinks("OSC %s" % O, ["%s_%s" % (o, k) for k in ("table", "pos", "warp", "wamt", "oct", "semi", "fine", "level",
                                                      "uni", "det", "blend", "width", "phase", "rand", "pan", "on")])

# ---- SUB / NOISE ----
out.append("\n[tab SUB NOISE]")
frame(0, "SUB")
ctl(0, 0, "seg", "SUB", "s_on")
ctl(0, 1, "popup", "SHAPE", "s_shape")
ctl(0, 2, "knob", "OCTAVE", "s_oct")
ctl(0, 3, "knob", "LEVEL", "s_level")
frame(1, "SUB OUT")
ctl(1, 0, "knob", "PAN", "s_pan")
ctl(1, 1, "seg", "ROUTE", "s_direct")
frame(2, "NOISE")
ctl(2, 0, "seg", "NOISE", "n_on")
ctl(2, 1, "popup", "TYPE", "n_type")
ctl(2, 2, "knob", "PITCH", "n_pitch")
ctl(2, 3, "knob", "LEVEL", "n_level")
frame(3, "NOISE OUT")
ctl(3, 0, "seg", "KEY TRACK", "n_key")
ctl(3, 1, "knob", "PAN", "n_pan")
help_text(["Sub Direct skips", "the filter", "", "Noise Pitch: rate of", "Digital and Crackle,", "colour of Hiss"])
qlinks("SUB NOISE", ["s_on", "s_shape", "s_oct", "s_level", "s_pan", "s_direct", "-", "-",
                     "n_on", "n_type", "n_pitch", "n_level", "n_key", "n_pan", "-", "-"])

# ---- FILTER ----
out.append("\n[tab FILTER]")
frame(0, "FILTER")
ctl(0, 0, "seg", "FILTER", "f_on")
ctl(0, 1, "popup", "TYPE", "f_type")
ctl(0, 2, "knob", "CUTOFF", "f_cut")
ctl(0, 3, "knob", "RESONANCE", "f_res")
frame(1, "SHAPE")
ctl(1, 0, "knob", "DRIVE", "f_drive")
ctl(1, 1, "knob", "KEY TRACK", "f_key")
ctl(1, 2, "knob", "ENV 2 AMT", "f_env")
ctl(1, 3, "knob", "MIX", "f_mix")
frame(2, "ROUTING")
ctl(2, 0, "seg", "OSC A", "f_ra")
ctl(2, 1, "seg", "OSC B", "f_rb")
ctl(2, 2, "seg", "NOISE", "f_rn")
ctl(2, 3, "seg", "SUB", "f_rs")
frame(3, "ENV 2")
for i, k in enumerate(("a", "d", "s", "r")):
    ctl(3, i, "knob", ("ATTACK", "DECAY", "SUSTAIN", "RELEASE")[i], "e2_%s" % k)
help_text(["Routing Off: that", "source skips the", "filter", "", "Formant: cutoff", "sweeps the vowels", "",
           "Comb: cutoff sets", "the pitch"])
qlinks("FILTER", ["f_on", "f_type", "f_cut", "f_res", "f_drive", "f_key", "f_env", "f_mix",
                  "f_ra", "f_rb", "f_rn", "f_rs", "e2_a", "e2_d", "e2_s", "e2_r"])

# ---- ENV ----
out.append("\n[tab ENV]")
for e in range(4):
    frame(e, "ENV %d%s" % (e + 1, " (AMP)" if e == 0 else ""))
    for i, k in enumerate(("a", "d", "s", "r")):
        ctl(e, i, "knob", ("ATTACK", "DECAY", "SUSTAIN", "RELEASE")[i], "e%d_%s" % (e + 1, k))
help_text(["Env 1 is the amp", "Env 2 has its own", "filter amount", "", "All four are mod", "sources"])
qlinks("ENV", ["e%d_%s" % (e, k) for e in range(1, 5) for k in ("a", "d", "s", "r")])

# ---- LFO (two sub-pages) ----
out.append("\n[tab LFO]")
for l in range(4):
    frame(l, "LFO %d" % (l + 1), "LFO")
    ctl(l, 0, "popup", "SHAPE", "l%d_shape" % (l + 1), "LFO")
    ctl(l, 1, "knob", "RATE", "l%d_rate" % (l + 1), "LFO")
    ctl(l, 2, "popup", "SYNC", "l%d_sync" % (l + 1), "LFO")
    ctl(l, 3, "seg", "MODE", "l%d_mode" % (l + 1), "LFO", n=3)
    frame(l, "LFO %d" % (l + 1), "LFO RISE")
    ctl(l, 0, "knob", "RISE", "l%d_rise" % (l + 1), "LFO RISE")
    ctl(l, 1, "knob", "PHASE", "l%d_phase" % (l + 1), "LFO RISE")
help_text(["Free: one LFO for", "all voices", "Retrig: restarts", "on each note", "Env: one cycle,", "then holds", "",
           "Press LFO again", "for rise and phase"])
qlinks("LFO", ["l%d_%s" % (l, k) for l in range(1, 5) for k in ("shape", "rate", "sync", "mode")])
qlinks("LFO RISE", [k for l in range(1, 5) for k in ("l%d_rise" % l, "l%d_phase" % l, "-", "-")])

# ---- MOD (four sub-pages of four slots) ----
out.append("\n[tab MOD]")
groups = ",".join("%s:%d" % (g, len(lst)) for g, lst in mp.DEST_GROUPS)
for page in range(4):
    title = "MOD %d-%d" % (page * 4 + 1, page * 4 + 4)
    for c in range(4):
        m = page * 4 + c + 1
        frame(c, "SLOT %d" % m, title)
        ctl(c, 0, "popup", "SOURCE", "m%d_src" % m, title)
        ctl(c, 1, "popup", "AUX", "m%d_aux" % m, title)
        out.append('popup cx=%d cy=%d w=216 h=44 label="DESTINATION" key=m%d_dst cw=118 groups="%s"%s'
                   % (CX[c], TOPS[2] + 64, m, groups, bk(title)))
        ctl(c, 3, "knob", "AMOUNT", "m%d_amt" % m, title)
help_text(["Source x Aux", "x Amount", "-> Destination", "Aux Off = x1", "", "LFOs are -1..1,", "envelopes 0..1", "",
           "Press MOD again", "for slots 5-16"])
for page in range(4):
    qlinks("MOD %d-%d" % (page * 4 + 1, page * 4 + 4),
           ["m%d_%s" % (page * 4 + c + 1, k) for c in range(4) for k in ("src", "aux", "dst", "amt")])

# ---- FX rack (two sub-pages of four slots) ----
out.append("\n[tab FX]")
for page in range(2):
    title = "FX %d-%d" % (page * 4 + 1, page * 4 + 4)
    for c in range(4):
        s = page * 4 + c + 1
        frame(c, "SLOT %d" % s, title)
        out.append('popup cx=%d cy=172 w=216 h=40 label="EFFECT" key=fx%d_type%s' % (CX[c], s, bk(title)))
        for i, k in enumerate(("p1", "p2", "p3", "mix")):
            out.append('knob cx=%d cy=%d r=24 label="%s" key=fx%d_%s%s' % (CX[c], 232 + 117 * i, k.upper(), s, k, bk(title)))
help_text(["Slots run in order,", "1 to 8", "", "Each knob is named", "after its slot's", "effect", "",
           "Press FX again", "for slots 5-8"])
for page in range(2):
    qlinks("FX %d-%d" % (page * 4 + 1, page * 4 + 4),
           ["fx%d_%s" % (page * 4 + c + 1, k) for c in range(4) for k in ("p1", "p2", "p3", "mix")])

if __name__ == "__main__":
    open(os.path.join(HERE, "layout.conf"), "w").write("\n".join(out) + "\n")
    print("layout.conf: %d lines" % len(out))
